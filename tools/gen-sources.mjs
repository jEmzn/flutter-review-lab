#!/usr/bin/env node
// Copies the real Dart sources used by the walkthroughs / bug hunt into js/data/sources.js
// (the site runs from file://, where fetch() of local files is blocked — so sources must be a script).
// Usage: node tools/gen-sources.mjs        (re-run whenever ex_13 or review_final_app changes)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ws = resolve(site, '..');
const RFA = 'review_final_app/lib/chapters/';
const FILES = {
  // key in FR.data.sources : path relative to the workspace (mb-works/)
  'ex13/pubspec.yaml': 'ex_13/pubspec.yaml',
  'ex13/lib/main.dart': 'ex_13/lib/main.dart',
  'ex13/lib/models/my_transaction.dart': 'ex_13/lib/models/my_transaction.dart',
  'ex13/lib/providers/transaction_provider.dart': 'ex_13/lib/providers/transaction_provider.dart',
  'ex13/lib/screens/transaction_list_screen.dart': 'ex_13/lib/screens/transaction_list_screen.dart',
  'ex13/lib/screens/add_edit_transaction_screen.dart': 'ex_13/lib/screens/add_edit_transaction_screen.dart',
  'ex13/test/my_transaction_test.dart': 'ex_13/test/my_transaction_test.dart',
  'ex13/test/add_edit_transaction_screen_test.dart': 'ex_13/test/add_edit_transaction_screen_test.dart',
  'offline/ch12/services/api_service.dart': RFA + 'ch12/services/api_service.dart',
  'offline/ch12/models/todo.dart': RFA + 'ch12/models/todo.dart',
  'offline/ch13/todo_offline/data/app_database.dart': RFA + 'ch13/todo_offline/data/app_database.dart',
  'offline/ch13/todo_offline/repositories/todo_repository.dart': RFA + 'ch13/todo_offline/repositories/todo_repository.dart',
  'offline/ch13/todo_offline/providers/todo_provider.dart': RFA + 'ch13/todo_offline/providers/todo_provider.dart',
  'offline/ch13/todo_offline/screens/todo_list_screen.dart': RFA + 'ch13/todo_offline/screens/todo_list_screen.dart',
  'offline/ch13/todo_offline/screens/todo_offline_app.dart': RFA + 'ch13/todo_offline/screens/todo_offline_app.dart',
  'rfa/ch13/exam_book/providers/book_provider.dart': RFA + 'ch13/exam_book/providers/book_provider.dart',
  'rfa/ch13/notes/helpers/database_helper.dart': RFA + 'ch13/notes/helpers/database_helper.dart',
  'rfa/ch13/expense/providers/transaction_provider.dart': RFA + 'ch13/expense/providers/transaction_provider.dart',
};

const out = {};
const missing = [];
for (const [key, rel] of Object.entries(FILES)) {
  const p = join(ws, rel);
  if (!existsSync(p)) { missing.push(rel); continue; }
  out[key] = readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
}
const header = `/* GENERATED by tools/gen-sources.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.\n   Real source files from ex_13/ and review_final_app/ for the walkthroughs and bug hunt. */\n`;
const body = `window.FR = window.FR || {};\nFR.data = FR.data || {};\nFR.data.sources = ${JSON.stringify(out, null, 1)};\nFR.data.sourcePaths = ${JSON.stringify(FILES, null, 1)};\n`;
mkdirSync(join(site, 'js/data'), { recursive: true });
writeFileSync(join(site, 'js/data/sources.js'), header + body);
console.log(`wrote js/data/sources.js — ${Object.keys(out).length} files` + (missing.length ? `, MISSING: ${missing.join(', ')}` : ''));
